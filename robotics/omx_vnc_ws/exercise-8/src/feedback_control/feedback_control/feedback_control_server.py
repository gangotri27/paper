#!/usr/bin/env python3
"""
feedback_control_server.py

Feedback-driven pick & place server (Exercise 8 style)
- Service: /perform_feedback (type: feedback_control_interface/FeedbackControl)
- Publishes JointTrajectory single-point commands to /arm_controller/joint_trajectory
- Uses /joint_states to confirm convergence (|err| < EPS for N_CONSEC cycles)
- Uses gripper action at /gripper_controller/gripper_cmd (control_msgs/action/GripperCommand)
- One retry per step, then recovery to HOME
- No time.sleep() — uses rclpy.spin_once polling loops
"""

import math
from collections import deque
from typing import List, Tuple

import rclpy
from rclpy.node import Node
from rclpy.action import ActionClient
from sensor_msgs.msg import JointState
from trajectory_msgs.msg import JointTrajectory, JointTrajectoryPoint
from builtin_interfaces.msg import Duration

# action / message imports
from control_msgs.action import GripperCommand as GripperCommandAction
from control_msgs.msg import GripperCommand as GripperCommandMsg

# service type (generated by feedback_control_interface)
from feedback_control_interface.srv import FeedbackControl

# -----------------------------
# Config (tune if required)
# -----------------------------
TRAJ_TOPIC = "/arm_controller/joint_trajectory"
GRIPPER_ACTION = "/gripper_controller/gripper_cmd"

JOINTS = ["joint1", "joint2", "joint3", "joint4"]

# Poses (example tuned for OM-X-style arm)
POSE_HOME  = [0.0, 0.0, 0.0, 0.0]
POSE_ABOVE = [0.0, 0.8, -0.6, 0.0]   # above object
POSE_LOWER = [0.0, 1.0, -0.7, 0.0]   # lowered pick pose
POSE_LIFT  = [0.0, 0.7, -0.5, 0.0]   # lift after grasp
POSE_PLACE = [0.4, 0.6, -0.5, 0.2]  # place pose

GRIP_CLOSE = 0.0
GRIP_OPEN  = 0.015

# Feedback / timeout tuning
EPS = 0.04                 # rad tolerance
CYCLE_PERIOD = 0.05        # seconds (20 Hz)
N_CONSEC = 4               # consecutive cycles required
STEP_TIMEOUT = 20.0        # seconds per step
GRIPPER_TIMEOUT = 8.0      # seconds for gripper action accept/result
RETRY_LIMIT = 1            # number of retries (one extra attempt)

# -----------------------------
# Server node
# -----------------------------
class FeedbackControlServer(Node):
    def __init__(self):
        super().__init__("feedback_control_server")

        # Service
        self.srv = self.create_service(FeedbackControl, "perform_feedback", self.handle_request)

        # Publisher & subscriber
        self.arm_pub = self.create_publisher(JointTrajectory, TRAJ_TOPIC, 10)
        self.js_sub = self.create_subscription(JointState, "/joint_states", self.joint_state_cb, 10)

        # Gripper action client
        self.gripper_client = ActionClient(self, GripperCommandAction, GRIPPER_ACTION)

        # state
        self.latest_js_map = None  # dict name -> position
        self.js_hist = deque(maxlen=50)
        self.step_logs = []

        self.get_logger().info("FeedbackControl server ready — waiting for service calls.")

    # ----------------------------
    # joint state callback
    # ----------------------------
    def joint_state_cb(self, msg: JointState):
        mapping = {n: p for n, p in zip(msg.name, msg.position)}
        self.latest_js_map = mapping
        self.js_hist.append(mapping)

    # ----------------------------
    # helper: current positions for JOINTS (returns list or None)
    # ----------------------------
    def current_positions(self) -> List[float] or None:
        if not self.latest_js_map:
            return None
        vals = []
        for j in JOINTS:
            if j not in self.latest_js_map:
                return None
            vals.append(self.latest_js_map[j])
        return vals

    # ----------------------------
    # publish single-point JointTrajectory (non-blocking)
    # ----------------------------
    def publish_pose(self, positions: List[float], duration: float = 2.0):
        msg = JointTrajectory()
        msg.joint_names = JOINTS
        pt = JointTrajectoryPoint()
        pt.positions = positions
        # set time_from_start
        sec = int(math.floor(duration))
        nsec = int((duration - sec) * 1e9)
        pt.time_from_start = Duration(sec=sec, nanosec=nsec)
        msg.points = [pt]
        self.arm_pub.publish(msg)
        self.get_logger().debug(f"Published trajectory: {positions} dur={duration}")

    # ----------------------------
    # convergence: wait until all JOINTS within EPS for N_CONSEC cycles
    # ----------------------------
    def wait_for_convergence(self, target: List[float], timeout_sec: float = STEP_TIMEOUT) -> Tuple[bool, float, str]:
        start = self.get_clock().now().nanoseconds
        consec = 0
        max_nanos = int(timeout_sec * 1e9)
        cycle = CYCLE_PERIOD

        while True:
            rclpy.spin_once(self, timeout_sec=cycle)
            now = self.get_clock().now().nanoseconds
            elapsed_ns = now - start
            if elapsed_ns > max_nanos:
                duration = elapsed_ns / 1e9
                return False, duration, "timeout"

            cur = self.current_positions()
            if cur is None:
                consec = 0
                continue

            errs = [abs(cur[i] - target[i]) for i in range(len(JOINTS))]
            max_err = max(errs)
            if max_err <= EPS:
                consec += 1
            else:
                consec = 0

            if consec >= N_CONSEC:
                duration = (now - start) / 1e9
                return True, duration, "converged"

    # ----------------------------
    # gripper action wrapper: send goal, wait for accept & result (polling)
    # returns (ok, duration, reason)
    # ----------------------------
    def gripper_set(self, position: float, timeout_sec: float = GRIPPER_TIMEOUT) -> Tuple[bool, float, str]:
        if not self.gripper_client.wait_for_server(timeout_sec=1.0):
            return False, 0.0, "no_gripper_server"

        goal = GripperCommandAction.Goal()
        goal.command = GripperCommandMsg()
        goal.command.position = float(position)
        goal.command.max_effort = 1.0

        send_fut = self.gripper_client.send_goal_async(goal)
        start_ns = self.get_clock().now().nanoseconds

        # wait for acceptance
        while not send_fut.done():
            rclpy.spin_once(self, timeout_sec=0.05)
            if (self.get_clock().now().nanoseconds - start_ns) / 1e9 > timeout_sec:
                return False, (self.get_clock().now().nanoseconds - start_ns) / 1e9, "goal_accept_timeout"

        goal_handle = send_fut.result()
        if not goal_handle.accepted:
            return False, (self.get_clock().now().nanoseconds - start_ns) / 1e9, "rejected"

        res_fut = goal_handle.get_result_async()
        while not res_fut.done():
            rclpy.spin_once(self, timeout_sec=0.05)
            if (self.get_clock().now().nanoseconds - start_ns) / 1e9 > timeout_sec:
                return False, (self.get_clock().now().nanoseconds - start_ns) / 1e9, "result_timeout"

        duration = (self.get_clock().now().nanoseconds - start_ns) / 1e9
        return True, duration, "converged"

    # ----------------------------
    # run one step with retry (pose or gripper)
    # ----------------------------
    def run_step_with_retry(self, step_index: int, step: dict) -> bool:
        name = step["name"]
        stype = step["type"]
        target = step["target"]
        dur_cmd = step.get("duration", 2.0)

        attempts = 0
        while attempts <= RETRY_LIMIT:
            attempts += 1
            start_ns = self.get_clock().now().nanoseconds

            if stype == "pose":
                self.publish_pose(target, duration=dur_cmd)
                ok, took, reason = self.wait_for_convergence(target, timeout_sec=STEP_TIMEOUT)
            else:  # gripper
                ok, took, reason = self.gripper_set(target, timeout_sec=GRIPPER_TIMEOUT)

            self.step_logs.append({
                "index": step_index,
                "type": stype,
                "target": name if stype == "pose" else f"grip={name}",
                "ok": ok,
                "reason": reason,
                "duration": took,
                "attempt": attempts
            })

            # print the requested single-step line
            status = "OK" if ok else "FAIL"
            if stype == "pose":
                self.get_logger().info(f"[{step_index}/8] pose={name:6s} {status}  reason={reason}  duration={took:.2f}s")
            else:
                self.get_logger().info(f"[{step_index}/8] grip={name:6s} {status}  reason={reason}  duration={took:.2f}s")

            if ok:
                return True
            else:
                if attempts <= RETRY_LIMIT:
                    self.get_logger().warn(f"Retrying step {step_index} ({name}), attempt {attempts+1}/{RETRY_LIMIT+1}")
                else:
                    self.get_logger().error(f"Step {step_index} ({name}) failed after {attempts} attempts")
                    return False

    # ----------------------------
    # worker that executes the full sequence (runs in background thread)
    # ----------------------------
    def _task_worker(self):
        self.step_logs = []
        overall_ok = True

        # ordered steps (8 steps)
        steps = [
            {"type": "pose", "name": "home",  "target": POSE_HOME,  "duration": 2.0},
            {"type": "pose", "name": "ready", "target": POSE_ABOVE, "duration": 3.0},
            {"type": "pose", "name": "pick",  "target": POSE_LOWER, "duration": 5.0},
            {"type": "grip", "name": "close", "target": GRIP_CLOSE},
            {"type": "pose", "name": "lift",  "target": POSE_LIFT,  "duration": 3.0},
            {"type": "pose", "name": "place", "target": POSE_PLACE, "duration": 3.0},
            {"type": "grip", "name": "open",  "target": GRIP_OPEN},
            {"type": "pose", "name": "home",  "target": POSE_HOME,  "duration": 2.0}
        ]

        for idx, step in enumerate(steps, start=1):
            ok = self.run_step_with_retry(idx, step)
            if not ok:
                overall_ok = False
                self.get_logger().warn("Attempting recovery: moving to HOME")
                self.publish_pose(POSE_HOME, duration=2.0)
                ok_home, t_home, r_home = self.wait_for_convergence(POSE_HOME, timeout_sec=STEP_TIMEOUT)
                if ok_home:
                    self.get_logger().info("Recovery to HOME succeeded.")
                else:
                    self.get_logger().error("Recovery to HOME failed.")
                break

        # final summary
        self.get_logger().info("=== PICK-AND-PLACE SUMMARY ===")
        for e in self.step_logs:
            idx = e["index"]
            typ = e["type"]
            tgt = e["target"]
            ok = "OK" if e["ok"] else "FAIL"
            reason = e["reason"]
            dur = f"{e['duration']:.2f}s"
            self.get_logger().info(f"{idx:2d} | {typ:4s} | {tgt:12s} | {ok:4s} | {reason:12s} | {dur}")

        return overall_ok

    # ----------------------------
    # service callback: start background worker thread
    # ----------------------------
    def handle_request(self, request, response):
        self.get_logger().info("Received perform_feedback request; starting background pick-and-place.")
        from threading import Thread
        t = Thread(target=self._task_worker, daemon=True)
        t.start()
        response.success = True
        response.message = "started"
        return response


def main(args=None):
    rclpy.init(args=args)
    node = FeedbackControlServer()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
